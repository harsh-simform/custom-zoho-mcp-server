"""Browser sign-in: the OAuth authorization-code flow with PKCE and a loopback redirect, so the refresh
token no longer has to be generated by hand in a Self Client.

`authorize` opens (or prints) Zoho's consent URL, waits for the browser to be redirected back to a one-shot
server bound to 127.0.0.1, checks `state`, exchanges the code and returns the refresh token. It writes
nothing; the caller stores the token. No secret, code or token is ever logged or put in an error.
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import secrets
import time
from dataclasses import dataclass, replace
from http.server import BaseHTTPRequestHandler, HTTPServer
from typing import Callable
from urllib.parse import parse_qs, urlencode, urlsplit

from .auth import PostFn, TOKEN_TIMEOUT_SECONDS
from .config import VALID_DATA_CENTERS, Settings
from .errors import AuthError, ConfigError, UpstreamError, UsageError
from .transport import describe_transport_error, unreachable_hint

DEFAULT_PORT = 8765
LOGIN_TIMEOUT_SECONDS = 300
CALLBACK_PATH = "/callback"

# Read-only scopes only; the tool never writes to Zoho.
SCOPES = (
    "ZohoProjects.portals.READ",
    "ZohoProjects.projects.READ",
    "ZohoProjects.tasks.READ",
    "ZohoProjects.tasklists.READ",
    "ZohoProjects.milestones.READ",
    "ZohoProjects.bugs.READ",
    "ZohoProjects.users.READ",
    "ZohoProjects.tags.READ",
    "ZohoProjects.search.READ",
)

_PAGE = (
    "<!doctype html><meta charset=utf-8><title>zoho-projects-axi</title>"
    "<body style='font-family:sans-serif;margin:3em'><h2>{title}</h2><p>{body}</p></body>"
)


@dataclass(frozen=True)
class LoginResult:
    refresh_token: str = ""
    dc: str = "com"  # the data center the account lives in; differs from settings.dc when sign-in discovered it


# Zoho's callback `location` is a region code, not the domain suffix: .com reports "us", .com.au reports "au".
_LOCATION_TO_DC = {"us": "com", "eu": "eu", "in": "in", "au": "com.au", "jp": "jp"}


def data_center_for(location: str) -> str | None:
    """The `dc` for a callback `location` (region code or domain suffix), or None when it is not one we support."""
    if location in VALID_DATA_CENTERS:
        return location
    return _LOCATION_TO_DC.get(location)


def redirect_uri(port: int) -> str:
    return f"http://localhost:{port}{CALLBACK_PATH}"


def pkce_pair() -> tuple[str, str]:
    """(code_verifier, S256 code_challenge)."""
    verifier = secrets.token_urlsafe(64)  # 86 chars, inside RFC 7636's 43..128
    digest = hashlib.sha256(verifier.encode("ascii")).digest()
    return verifier, base64.urlsafe_b64encode(digest).rstrip(b"=").decode("ascii")


def authorization_url(settings: Settings, client_id: str, port: int, state: str, challenge: str) -> str:
    query = urlencode({
        "response_type": "code",
        "client_id": client_id,
        "scope": ",".join(SCOPES),
        "redirect_uri": redirect_uri(port),
        "state": state,
        "code_challenge": challenge,
        "code_challenge_method": "S256",
        "access_type": "offline",  # without these two Zoho returns no refresh token
        "prompt": "consent",
    })
    return f"{settings.accounts_base}/oauth/v2/auth?{query}"


class _CallbackServer(HTTPServer):
    allow_reuse_address = True
    callback: dict[str, str] | None = None


class _Handler(BaseHTTPRequestHandler):
    server: _CallbackServer

    def log_message(self, format: str, *args: object) -> None:  # the query string holds the code
        pass

    def _reply(self, status: int, title: str, body: str) -> None:
        payload = _PAGE.format(title=title, body=body).encode()
        self.send_response(status)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(payload)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(payload)

    def do_GET(self) -> None:
        parts = urlsplit(self.path)
        if parts.path != CALLBACK_PATH:
            self._reply(404, "Not found", "This is the zoho-projects-axi sign-in listener.")
            return
        params = {k: v[0] for k, v in parse_qs(parts.query).items()}
        if "code" not in params and "error" not in params:
            self._reply(400, "Bad request", "No authorization result in this request.")
            return
        self.server.callback = params
        if "error" in params:
            self._reply(400, "Sign-in failed", "Zoho did not grant access. You can close this tab.")
        else:
            self._reply(200, "Signed in", "zoho-projects-axi is authorized. You can close this tab and go back to the terminal.")


def _wait_for_callback(server: _CallbackServer, timeout: float, clock: Callable[[], float]) -> dict[str, str]:
    deadline = clock() + timeout
    server.timeout = 0.5
    while server.callback is None:
        if clock() >= deadline:
            raise AuthError(
                "auth.login_timeout",
                f"No sign-in response within {int(timeout)} seconds.",
                hint="Run `zoho-projects-axi auth login` again and finish the consent in the browser.",
            )
        server.handle_request()
    return server.callback


def authorize(
    settings: Settings,
    make_post: Callable[[Settings], PostFn],
    *,
    port: int = DEFAULT_PORT,
    announce: Callable[[str], None],
    open_browser: Callable[[str], bool] | None = None,
    timeout: float = LOGIN_TIMEOUT_SECONDS,
    clock: Callable[[], float] = time.monotonic,
) -> LoginResult:
    """Run the browser flow and return the refresh token and the data center it belongs to. `announce` gets
    the consent URL and progress lines (the CLI sends them to stderr); `open_browser` returns False when no
    browser could be launched. `make_post(settings)` gives the token-endpoint POST for that settings' data
    center: sign-in starts at `settings.dc`, and Zoho reports the account's real data center on the callback."""
    client_id, client_secret = settings.client_id, settings.client_secret
    if not client_id or not client_secret:
        raise AuthError(
            "auth.missing",
            "client_id and client_secret are needed before signing in.",
            hint=(
                "This build ships no Zoho client. Register a Server-based Application once "
                "(`zoho-projects-axi auth login-help`), then put its client_id "
                f"and client_secret in {settings.config_path} or ZOHO_PROJECTS_AXI_CLIENT_ID / ZOHO_PROJECTS_AXI_CLIENT_SECRET."
            ),
        )

    try:
        server = _CallbackServer(("127.0.0.1", port), _Handler)
    except OSError as exc:
        raise UsageError(
            "usage.port_unavailable",
            f"Cannot listen on 127.0.0.1:{port}: {exc.strerror or type(exc).__name__}",
            hint="Pick a free port with --port N and register http://localhost:N/callback as a redirect URI.",
        ) from None

    verifier, challenge = pkce_pair()
    state = secrets.token_urlsafe(24)
    url = authorization_url(settings, client_id, port, state, challenge)
    try:
        announce(f"Open this URL to sign in to Zoho:\n{url}")
        if open_browser is not None and not open_browser(url):
            announce("Could not open a browser here; open the URL above yourself.")
        announce(f"Waiting for the redirect on {redirect_uri(port)} ...")
        callback = _wait_for_callback(server, timeout, clock)
    finally:
        server.server_close()

    if not hmac.compare_digest(callback.get("state", ""), state):
        raise AuthError("auth.state_mismatch", "The sign-in response did not match this request; nothing was saved.",
                        hint="Run `zoho-projects-axi auth login` again and use only the URL it prints.")
    if "error" in callback:
        raise AuthError("auth.denied", f"Zoho refused the sign-in: {callback['error']}",
                        hint="Check the redirect URI registered for the client, then run `zoho-projects-axi auth login` again.")
    reported = callback.get("location")
    location = data_center_for(reported) if reported else settings.dc
    if location is None:  # the data center is placed in a hostname that gets the secret, so only known ones pass
        raise AuthError("auth.unsupported_data_center",
                        f"Zoho reported data center {reported[:20]!r}, which is not supported; nothing was saved.",
                        hint=f"Supported: {', '.join(VALID_DATA_CENTERS)}. Use a Self Client at your data center's "
                             "API console instead (`zoho-projects-axi auth login-help`).")
    account = settings if location == settings.dc else replace(settings, dc=location)
    post = make_post(account)

    try:
        body = post(
            f"{account.accounts_base}/oauth/v2/token",
            {
                "grant_type": "authorization_code",
                "client_id": client_id,
                "client_secret": client_secret,
                "redirect_uri": redirect_uri(port),
                "code": callback["code"],
                "code_verifier": verifier,
            },
            TOKEN_TIMEOUT_SECONDS,
        )
    except OSError as exc:
        raise UpstreamError(
            "upstream.unreachable",
            f"Could not reach {account.accounts_base}: {describe_transport_error(exc)}",
            hint=unreachable_hint(exc),
        ) from None

    refresh = body.get("refresh_token") if isinstance(body, dict) else None
    if not isinstance(refresh, str) or not refresh:
        reason = str(body.get("error", "no refresh_token in the response")) if isinstance(body, dict) else "unexpected response"
        raise AuthError(
            "auth.exchange_failed",
            f"Zoho did not return a refresh token: {reason}",
            hint=(
                "Check client_secret, that the redirect URI matches exactly, and that the code was used once. "
                f"A client registered only in the {settings.dc} data center cannot serve an account in {location}."
            ),
        )
    return LoginResult(refresh, location)
